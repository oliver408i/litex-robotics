/* Synchronous flush.
 *
 * LVGL issues MULTIPLE disjoint dirty areas in a single refresh (button press
 * feedback, the result+status+bars all updating on Classify, the initial UI
 * paint). The earlier async design fired a DMA op per area and relied on the
 * op-done ISR to signal flush_ready -- but with a single in-flight pointer and
 * a one-slot op queue, completions for multiple areas got miscounted, so LVGL
 * was told "done" for an area the engine was still shifting out. It then
 * re-rendered that widget into the framebuffer (direct mode re-renders changed
 * regions every frame to keep both buffers in sync) WHILE the engine was
 * DMA-reading those pixels -> torn reads -> mis-colored line glitches.
 *
 * The drawing canvas was immune only because it's white-on-black: re-rendering
 * white over white mid-read is invisible. Colored widgets are not.
 *
 * Fix: fire the op, drain the engine, THEN signal ready. LVGL can never touch
 * a region the engine is still reading. Cost is negligible -- drawing is one
 * small rect per frame; widget/full-screen redraws are infrequent. */
static void lvgl_flush_cb(lv_display_t *disp, const lv_area_t *area, uint8_t *px_map)
{
	uint16_t x1 = (uint16_t)area->x1;
	uint16_t x2 = (uint16_t)area->x2;
	uint16_t y1 = (uint16_t)area->y1;
	uint16_t y2 = (uint16_t)area->y2;
	uint32_t w  = (uint32_t)(x2 - x1 + 1);
	uint32_t h  = (uint32_t)(y2 - y1 + 1);

	uint32_t src_off  = ((uint32_t)y1 * LCD_WIDTH + x1) * 2u;
	uint32_t row_b    = w * 2u;
	uint32_t stride_b = (uint32_t)LCD_WIDTH * 2u;

	lcd_wait_can_accept();
	lcd_rect_x_write(((uint32_t)x2 << 16) | (uint32_t)x1);
	lcd_rect_y_write(((uint32_t)y2 << 16) | (uint32_t)y1);
	lcd_dma_src_write((uint32_t)px_map + src_off);
	lcd_dma_row_bytes_write(row_b);
	lcd_dma_row_count_write(h);
	lcd_dma_stride_write(stride_b);

	lcd_op_write(LCD_OP_DMA_RECT);

	lcd_wait_idle();                 /* drain before releasing the buffer to LVGL */
	lv_display_flush_ready(disp);
}

/* ======================================================================== */
/*  LVGL touch indev (from lvgl_demo)                                        */
/* ======================================================================== */

static void lvgl_touch_read_cb(lv_indev_t *indev, lv_indev_data_t *data)
{
	(void)indev;

	uint8_t buf[7];
	if(!ft6336u_read(0x02, buf, sizeof(buf))) {
		data->state = LV_INDEV_STATE_RELEASED;
		return;
	}

	unsigned int n = buf[0] & 0x0f;
	if(n == 0) {
		data->state = LV_INDEV_STATE_RELEASED;
		return;
	}
	unsigned int x = ((buf[1] & 0x0f) << 8) | buf[2];
	unsigned int y = ((buf[3] & 0x0f) << 8) | buf[4];

	if(x >= LCD_WIDTH)  x = LCD_WIDTH  - 1;
	if(y >= LCD_HEIGHT) y = LCD_HEIGHT - 1;
	data->point.x = (lv_coord_t)x;
	data->point.y = (lv_coord_t)y;
	data->state   = LV_INDEV_STATE_PRESSED;
}

