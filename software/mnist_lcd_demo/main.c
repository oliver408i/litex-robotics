/* ======================================================================== */
/*  main                                                                     */
/* ======================================================================== */

int main(void)
{
	uart_init();
#ifdef CONFIG_CPU_HAS_INTERRUPT
	irq_setie(1);
#endif

	log_puts("mnist_lcd_demo starting"); log_nl();
	log_puts("sys clk : "); log_uint(CONFIG_CLOCK_FREQUENCY); log_puts(" Hz"); log_nl();

	lcd_pads_apply();
	lcd_init();
	busy_wait(200);                  /* FT6336U wants ~200 ms after reset */
	touch_init();
	ft6336u_probe();

	snn_setup();
	log_puts("SNN weights @ 0x"); log_hex32((uint32_t)(uintptr_t)snn_weights_blob); log_nl();
	log_puts("LCD + touch + SNN ready"); log_nl();

	lvgl_tick_init();
	lv_init();
	lv_tick_set_cb(lvgl_tick_get_ms_cb);

	lv_display_t *disp = lv_display_create(LCD_WIDTH, LCD_HEIGHT);
	lv_display_set_color_format(disp, LV_COLOR_FORMAT_RGB565_SWAPPED);
	lv_display_set_buffers(disp, lvgl_fb1, lvgl_fb2, sizeof(lvgl_fb1),
	                       LV_DISPLAY_RENDER_MODE_DIRECT);
	lv_display_set_flush_cb(disp, lvgl_flush_cb);

	/* Flush is synchronous now (see lvgl_flush_cb); no op-done IRQ needed. */

	lv_indev_t *indev = lv_indev_create();
	lv_indev_set_type(indev, LV_INDEV_TYPE_POINTER);
	lv_indev_set_read_cb(indev, lvgl_touch_read_cb);

	build_ui();

	/* Direct render mode keeps two full framebuffers and paints only the
	 * active one per refresh, swapping between them. Both start black (.bss),
	 * so the first buffer swap would briefly show a half-painted frame. Prime
	 * BOTH by forcing two full-screen refreshes before the user sees anything. */
	for(int i = 0; i < 2; i++) {
		lv_obj_invalidate(lv_screen_active());
		lv_refr_now(disp);
	}

	/* Start logging at boot: LSM6DS3 FIFO -> SD card, stamped off the LVGL
	 * tick. Fails gracefully (Logger tab shows ERROR) if no card is present. */
	if(imu_log_start(lvgl_tick_get_ms_cb()) == 0)
		log_puts("imu_log: started");
	else
		log_puts("imu_log: start failed (no SD card / IMU?)");
	log_nl();

	log_puts("entering main loop"); log_nl();

	/* No busy_wait() past lvgl_tick_init() -- it reloads timer0. The logger
	 * drains the IMU FIFO each iteration; the hardware FIFO absorbs the jitter
	 * from LVGL's occasionally-long render frames. */
	for(;;) {
		(void)lv_timer_handler();
		imu_log_poll(lvgl_tick_get_ms_cb());
	}

	return 0;
}
