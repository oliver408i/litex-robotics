/* ---- Power tab: 2S LiPo battery gauge ------------------------------------ */
/* Voltage-only state of charge -- the brick's current sense can't resolve this
 * board's sub-1-LSB (~128 mA) draw, so amps/watts/mAh are meaningless here and
 * dropped. Sampled off a 250 ms LVGL timer (battery state is slow; two MCP3008
 * reads cost only tens of microseconds). */
#define POWER_PERIOD_MS 250

static lv_obj_t *pwr_v_label;     /* big pack voltage          */
static lv_obj_t *pwr_soc_bar;     /* state-of-charge gauge bar */
static lv_obj_t *pwr_soc_label;   /* "52 %"                    */
static lv_obj_t *pwr_cell_label;  /* per-cell voltage          */
static lv_obj_t *pwr_raw_label;   /* raw ADC code (debug)      */

static void power_timer_cb(lv_timer_t *t)
{
	(void)t;
	power_reading_t r;
	power_read(&r);

	unsigned pct     = battery_soc_pct(r.bus_mV);
	unsigned cell_mV = (unsigned)(r.bus_mV / BATTERY_CELLS);

	/* Integer formatting (no soft-float). */
	lv_label_set_text_fmt(pwr_v_label, "%u.%01u V",
	                      (unsigned)(r.bus_mV / 1000u),
	                      (unsigned)((r.bus_mV % 1000u) / 100u));
	lv_label_set_text_fmt(pwr_cell_label, "%u.%02u V/cell  (2S LiPo)",
	                      cell_mV / 1000u, (cell_mV % 1000u) / 10u);
	lv_label_set_text_fmt(pwr_soc_label, "%u%%", pct);
	lv_bar_set_value(pwr_soc_bar, (int)pct, LV_ANIM_OFF);

	/* Color by charge: green > 50, amber 20-50, red < 20 (low-battery cue). */
	lv_color_t c = (pct > 50)  ? lv_palette_main(LV_PALETTE_GREEN)
	             : (pct >= 20) ? lv_palette_main(LV_PALETTE_AMBER)
	                           : lv_palette_main(LV_PALETTE_RED);
	lv_obj_set_style_bg_color(pwr_soc_bar, c, LV_PART_INDICATOR);
	lv_obj_set_style_text_color(pwr_v_label,
	                            (pct < 20) ? c : lv_color_white(), 0);

	lv_label_set_text_fmt(pwr_raw_label, "adc v=%u  (i=%u unused)",
	                      (unsigned)r.v_code, (unsigned)r.i_code);
}

