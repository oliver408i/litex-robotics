static inline void snn_start_pulse(void) { snn_control_write(1u); }       /* bit0 start */
static inline void snn_clear_pulse(void) { snn_control_write(2u); }       /* bit1 clear_state */

static inline void snn_pixel_commit(uint16_t addr, int16_t data)
{
	snn_pixel_addr_write(addr);
	snn_pixel_data_write((uint16_t)data);
	snn_pixel_ctl_write(1u);                                              /* .we pulse */
}
static inline void snn_bias_commit(uint16_t addr, int16_t data)
{
	snn_bias_addr_write(addr);
	snn_bias_data_write((uint16_t)data);
	snn_bias_ctl_write(1u);                                               /* .we pulse */
}
static inline int snn_done(void)           { return (snn_status_read() >> 1) & 1u; }
static inline uint8_t snn_classification(void) { return (uint8_t)((snn_status_read() >> 5) & 0xFu); }

static uint8_t spike_count_read(int i)
{
	switch(i) {
	case 0:  return (uint8_t)snn_spike_count_0_read();
	case 1:  return (uint8_t)snn_spike_count_1_read();
	case 2:  return (uint8_t)snn_spike_count_2_read();
	case 3:  return (uint8_t)snn_spike_count_3_read();
	case 4:  return (uint8_t)snn_spike_count_4_read();
	case 5:  return (uint8_t)snn_spike_count_5_read();
	case 6:  return (uint8_t)snn_spike_count_6_read();
	case 7:  return (uint8_t)snn_spike_count_7_read();
	case 8:  return (uint8_t)snn_spike_count_8_read();
	case 9:  return (uint8_t)snn_spike_count_9_read();
	default: return 0;
	}
}

/* One-time loader/bias setup. The weight blob lives in .rodata (SDRAM); point
 * the loader straight at it. The flush is mandatory: the loader's DMA reads via
 * a dedicated native SDRAM port that BYPASSES the L2, so dirty CPU writes must
 * be pushed out to physical SDRAM first (see docs/snn_mnist.md "LiteDRAM L2
 * coherence"). */
static void snn_setup(void)
{
	snn_weight_base_write((uint32_t)(uintptr_t)snn_weights_blob);
	snn_weight_preamble_beats_write(SNN_PREAMBLE_BEATS);
	snn_weight_beats_per_cycle_write(SNN_BEATS_PER_CYCLE);
	snn_weight_num_cycles_write(SNN_NUM_CYCLES);

	for(int i = 0; i < SNN_BIAS_COUNT; i++)
		snn_bias_commit((uint16_t)i, snn_biases[i]);

	flush_cpu_dcache();
#ifdef CONFIG_L2_SIZE
	flush_l2_cache();
#endif
}

/* ======================================================================== */
/*  LVGL tick source (from lvgl_demo) -- timer0 free-running countdown       */
/* ======================================================================== */

static uint32_t tick_prev_cycles;
static uint32_t tick_accum_ms;
static uint32_t tick_cycles_carry;

static uint32_t lvgl_tick_get_ms_cb(void)
{
	timer0_update_value_write(1);
	uint32_t now   = timer0_value_read();
	uint32_t delta = (tick_prev_cycles - now) + tick_cycles_carry;
	tick_prev_cycles = now;

	uint32_t cycles_per_ms = CONFIG_CLOCK_FREQUENCY / 1000u;
	tick_accum_ms     += delta / cycles_per_ms;
	tick_cycles_carry  = delta % cycles_per_ms;
	return tick_accum_ms;
}

static void lvgl_tick_init(void)
{
	timer0_en_write(0);
	timer0_load_write(0xffffffffu);
	timer0_reload_write(0xffffffffu);
	timer0_en_write(1);
	timer0_update_value_write(1);
	tick_prev_cycles  = timer0_value_read();
	tick_accum_ms     = 0;
	tick_cycles_carry = 0;
}

